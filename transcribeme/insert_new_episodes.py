def insert_before(path: Path, marker: str, block: str, label: str):
    t = path.read_text(encoding="utf-8", errors="replace")
    if "THE FINGERPRINT" in t and "BONUS EPISODE 5" in t:
        print(f"{path.name}: already has new episodes")
        return
    if marker not in t:
        print(f"{path.name}: MARKER NOT FOUND: {marker}")
        return
    t = t.replace(marker, block.strip() + "\n\n---\n\n" + marker, 1)
    path.write_text(t, encoding="utf-8")
    print(f"{path.name}: inserted {label} -> {len(t)} bytes")


